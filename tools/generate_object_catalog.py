"""Generate the compact, factual editor-ID catalog; no names are redistributed.

Download objects.csv from the pinned source URL below, then run:
    python3 tools/generate_object_catalog.py /path/to/objects.csv [--check]
The game never downloads or parses this file at runtime.
"""
import argparse
import csv
import hashlib
import io
from pathlib import Path

SOURCE = "https://raw.githubusercontent.com/Alphalaneous/GDObjectNames/8b74b132c55cbee6231a035c656dd1224e37a7cb/objects.csv"
SHA256 = "c061319df641824db98ff190cff29b2bdc479d59968d6e4012b3e08283447602"
# Legacy color triggers absent from the editor catalog, audited against
# geode-sdk/bindings b17b28de467984a31ad7994920a593a8b9d14ea3:
# bindings/2.2081/inline/GameObject.cpp, GameObject::isColorTrigger.
LEGACY = {29, 30, 105, 744, 900, 915}


def generate(raw):
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise ValueError("Input does not match the pinned object catalog")
    rows = list(csv.reader(io.StringIO(raw.decode("utf-8"))))
    ids = {int(row[0]) for row in rows}
    if len(rows) != 3987 or len(ids) != len(rows) or min(ids) != 1 or max(ids) != 4539:
        raise ValueError("Unexpected ID count or range")
    ids |= LEGACY
    words = [0] * (max(ids) // 64 + 1)
    for object_id in ids:
        words[object_id // 64] |= 1 << (object_id % 64)
    literals = "\n".join(
        "    " + ", ".join(f"0x{word:016x}ULL" for word in words[i:i + 4]) + ","
        for i in range(0, len(words), 4)
    )
    return f"""// Generated by tools/generate_object_catalog.py; factual IDs only.
// Source: {SOURCE}
// Source SHA256: {SHA256}
// 3987 catalog entries + 6 audited legacy color IDs. Not a collision whitelist.
#pragma once
#include <array>
#include <cstdint>

namespace dynamic {{
inline constexpr unsigned objectCatalogCount = {len(ids)};
inline constexpr std::array<std::uint64_t, {len(words)}> objectCatalogBits{{{{
{literals}
}}}};
constexpr bool knownObjectID(int id) {{
    return id > 0 && id <= 4539 &&
        ((objectCatalogBits[static_cast<unsigned>(id) / 64] >> (id % 64)) & 1ULL) != 0;
}}
}} // namespace dynamic
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate(args.csv.read_bytes())
    output = Path(__file__).resolve().parents[1] / "src" / "object_catalog.hpp"
    if args.check:
        if output.read_text() != result:
            raise SystemExit("Generated catalog is stale")
    else:
        output.write_text(result)
    print("Verified 3993 IDs (3987 catalog + 6 legacy); 568 bytes of lookup data")


if __name__ == "__main__":
    main()
